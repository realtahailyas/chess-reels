"""Thirty days of promotion, as a schedule you can BUILD, not just read.

    python content_plan.py                 # print the calendar
    python content_plan.py --day 1         # what to make for day 1
    python content_plan.py --build 1       # actually make it
    python content_plan.py --build 1-7     # a week in one go
    python content_plan.py --export        # plan.json + PLAN.md

ONE ASSET GOES EVERYWHERE. A 1080x1920 reel is a Reel, a Short and a Facebook
Reel with no re-export, and the 4:5 carousel posts to Instagram and Facebook as
is (YouTube gets that day's reel instead). Cutting three versions of the same
idea triples the work and changes nothing about how it performs.

THE SHAPE OF THE MONTH
  * A named beat per weekday, so the account has a rhythm somebody can follow.
  * The MOTIF rotates through the app's own seventeen themes, so "another
    puzzle reel" is never the same puzzle reel twice.
  * The RATING BAND rotates too. A month of 2200-rated positions reads as
    showing off; a month of 900s reads as beginner content. It alternates.
  * The two evergreen films (the app tour and the bot ladder) are built ONCE
    and re-posted weekly, because they are the only pieces that pitch the whole
    app rather than one tactic.
"""

