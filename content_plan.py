# weekday -> (beat name, [(variant, count), ...])
# Weekends carry a fourth piece: the time people scroll longest.
# MOTION and MEME are cheap (no puzzle, no ledger) and they are what stops a
# month of boards reading as one long video. One of each most days.
RHYTHM = {
    0: ("Mate Monday", [("promo_mate", 1), ("MOTION", 1), ("promo_carousel", 1)]),
    1: ("Tactic Tuesday", [("promo_guess", 1), ("REACTION", 1), ("MEME", 1)]),
    2: ("Sacrifice Wednesday", [("REACTION", 2), ("MOTION", 1), ("promo_carousel", 1)]),
    3: ("Grandmaster Thursday", [("gm_games", 1), ("promo_guess", 1), ("MOTION", 1)]),
    4: ("Feature Friday", [("EVERGREEN", 1), ("REACTION", 1), ("MEME", 1)]),
    5: ("Speedrun Saturday", [("promo_mate", 1), ("MOTION", 1), ("promo_carousel", 1),
                              ("MEME", 1)]),
    6: ("Sunday Reset", [("promo_guess", 1), ("REACTION", 1), ("MOTION", 1),
                         ("EVERGREEN", 1)]),
}

# Built once, re-posted. Alternate so neither goes out twice in a week.
EVERGREEN = ["promo_tour", "promo_bots"]

PLATFORMS = "Instagram Reels · YouTube Shorts · Facebook Reels"
PLATFORMS_STILL = "Instagram · Facebook"


def plan(days: int = 30, start: date = None) -> list:
    """The whole month. Deterministic — same start date, same plan."""
    start = start or date.today()
    out, n = [], 0
    for i in range(days):
        day = start + timedelta(days=i)
        beat, slots = RHYTHM[day.weekday()]
        week = i // 7
        items = []
        for variant, count in slots:
            for _ in range(count):
                if variant == "EVERGREEN":
                    name = EVERGREEN[(week + len(items)) % len(EVERGREEN)]
                    items.append(_evergreen_item(name, n))
                elif variant == "MOTION":
                    items.append(_motion_item(MOTION[n % len(MOTION)], n, "motion"))
                elif variant == "MEME":
                    items.append(_motion_item(MOTION_MEME[n % len(MOTION_MEME)],
                                              n, "meme"))
                elif variant == "REACTION":
                    items.append(_item(REACTION[n % len(REACTION)], n))
                else:
                    items.append(_item(variant, n))
                n += 1
        out.append({"day": i + 1, "date": day.isoformat(),
                    "weekday": day.strftime("%a"), "beat": beat, "items": items})
    return out


def _item(variant: str, n: int) -> dict:
    theme = THEME_CYCLE[n % len(THEME_CYCLE)]
    band, lo, hi = BANDS[n % len(BANDS)]
    hooks = HOOKS[variant]
    still = variant == "promo_carousel"
    item = {
        "variant": variant,
        "theme": theme,
        "band": band,
        "rating": [lo, hi],
        "hook": hooks[n % len(hooks)],
        "angle": ANGLES[n % len(ANGLES)],
        "platforms": PLATFORMS_STILL if still else PLATFORMS,
        "evergreen": False,
    }
    # promo_mate carries its own theme filter; overriding it with "fork" would
    # produce a mate reel that is not a mate.
    if variant in ("promo_mate", "gm_games"):
        item["theme"] = None
    item["cmd"] = _cmd(item)
    return item


def _motion_item(comp: str, n: int, kind: str) -> dict:
    """A Remotion composition. No puzzle, so no theme, band or ledger entry."""
    hooks = HOOKS[kind]
    return {
        "variant": f"motion:{comp}",
        "theme": None,
        "band": None,
        "rating": None,
        "hook": hooks[n % len(hooks)],
        "angle": ANGLES[n % len(ANGLES)],
        "platforms": PLATFORMS,
        "evergreen": False,
        "cmd": f"python render_motion.py {comp}",
    }


def _evergreen_item(variant: str, n: int) -> dict:
    item = {
        "variant": variant, "theme": None, "band": None, "rating": None,
        "hook": HOOKS[variant][n % len(HOOKS[variant])],
        "angle": "point at the store, once, plainly",
        "platforms": PLATFORMS, "evergreen": True,
        "cmd": f"python run_batch.py --variant {variant}",
    }
    return item


def _cmd(item: dict) -> str:
    parts = ["python run_batch.py", f"--variant {item['variant']}", "--count 1"]
    if item["theme"]:
        parts.append(f"--theme {item['theme']}")
    if item["rating"]:
        parts.append(f"--rating-min {item['rating'][0]} --rating-max {item['rating'][1]}")
    return " ".join(parts)


def show(days: list, verbose: bool = False) -> None:
    for d in days:
        print(f"\n── Day {d['day']:2}  {d['date']}  {d['weekday']}  ·  {d['beat']}")
        for it in d["items"]:
            tag = "evergreen, repost" if it["evergreen"] else \
                  f"{it['theme'] or '—'}, {it['band'] or '—'}"
            print(f"     {it['variant']:16} {tag}")
            print(f"       hook   “{it['hook']}”")
            if verbose:
                print(f"       angle  {it['angle']}")
                print(f"       post   {it['platforms']}")
                print(f"       build  {it['cmd']}")


def build(days: list, log=print) -> int:
    """Run each day's commands. Evergreens are built once, not per post."""
    seen, failed = set(), 0
    for d in days:
        log(f"\n=== Day {d['day']} · {d['beat']} ===")
        for it in d["items"]:
            if it["evergreen"]:
                if it["variant"] in seen:
                    log(f"  skip   {it['variant']} — already built, this is a repost")
                    continue
                seen.add(it["variant"])
            log(f"  build  {it['cmd']}")
            r = subprocess.run([sys.executable] + it["cmd"].split()[1:], cwd=ROOT, creationflags=config.SUBPROCESS_NO_WINDOW)
            failed += r.returncode != 0
    return failed


def _parse_days(spec: str, days: list) -> list:
    if "-" in spec:
        a, b = (int(x) for x in spec.split("-", 1))
        return [d for d in days if a <= d["day"] <= b]
    n = int(spec)
    return [d for d in days if d["day"] == n]


def export(days: list) -> None:
    (ROOT / "plan.json").write_text(json.dumps(days, indent=2), encoding="utf-8")
    lines = ["# Thirty days of TChess promotion", "",
             f"One asset per slot, posted to **{PLATFORMS}** unchanged.", ""]
    for d in days:
        lines.append(f"## Day {d['day']} — {d['date']} ({d['weekday']}) · {d['beat']}")
        for it in d["items"]:
            what = "evergreen (repost)" if it["evergreen"] else \
                   f"{it['theme'] or 'any'} · {it['band'] or '—'}"
            lines += [f"- **{it['variant']}** — {what}",
                      f"  - Hook: *{it['hook']}*",
                      f"  - Caption should: {it['angle']}",
                      f"  - Post to: {it['platforms']}",
                      f"  - Build: `{it['cmd']}`"]
        lines.append("")
    (ROOT / "PLAN.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {ROOT / 'plan.json'} and {ROOT / 'PLAN.md'}")


def main(argv=None) -> int:
    # The Windows console is cp1252 and this script prints box rules, curly
    # quotes and middots. Without this the whole run dies on the first print —
    # the same trap that once made a finished Play upload look like a crash.
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except (AttributeError, OSError):
        pass

    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--days", type=int, default=30)
    ap.add_argument("--start", help="YYYY-MM-DD; defaults to today")
    ap.add_argument("--day", help="show one day or a range, e.g. 1 or 1-7")
    ap.add_argument("--build", help="build one day or a range")
    ap.add_argument("--export", action="store_true")
    ap.add_argument("--verbose", action="store_true")
    args = ap.parse_args(argv)

    start = date.fromisoformat(args.start) if args.start else date.today()
    days = plan(args.days, start)

    if args.build:
        return build(_parse_days(args.build, days))
    if args.export:
        export(days)
        return 0

    show(_parse_days(args.day, days) if args.day else days,
         verbose=args.verbose or bool(args.day))
    total = sum(len(d["items"]) for d in days)
    print(f"\n{len(days)} days · {total} pieces · "
          f"{total / len(days):.1f} per day")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
